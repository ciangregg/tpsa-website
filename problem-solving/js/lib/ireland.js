export const IRELAND = (() => {
  const k = Math.cos(53.2 * Math.PI / 180);
  const pts = IRELAND_RAW.map(([lo, la]) => [lo * k, la]);
  let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9;
  for (const [x, y] of pts) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
  const span = Math.max(maxX - minX, maxY - minY);
  return pts.map(([x, y]) => [(x - minX) / span, (maxY - y) / span]);
})();

export const IB = IRELAND.reduce((b, [x, y]) => ({
  minX: Math.min(b.minX, x), maxX: Math.max(b.maxX, x),
  minY: Math.min(b.minY, y), maxY: Math.max(b.maxY, y),
}), { minX: 1, maxX: 0, minY: 1, maxY: 0 });

export const IB_AR = (IB.maxX - IB.minX) / (IB.maxY - IB.minY);

export function pointInPoly(px, py, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][0], yi = poly[i][1], xj = poly[j][0], yj = poly[j][1];
    if ((yi > py) !== (yj > py) && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
